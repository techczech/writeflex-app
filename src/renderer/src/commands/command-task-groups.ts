/** The task group and sub-group of a command id. Throws for an id with none, so a new command cannot ship ungrouped. */
export const taskGroupOf = (id: string): { task: TaskGroup; subgroup: string } => {
  const entry = commandTaskGroups[id]
  if (!entry) throw new Error(`Command has no task group: ${id} (add it to commands/command-task-groups.ts)`)
  return { task: entry[0], subgroup: entry[1] }
}
