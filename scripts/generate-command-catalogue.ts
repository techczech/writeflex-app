// Writes src/shared/command-catalogue.ts: every palette command of the renderer's registry
// (src/renderer/src/commands/registry.ts) as plain data, so main (the menu bar, the Settings window's
// Shortcuts page, the settings file's shortcut overrides) and the settings CLI read the same list
// without bundling CodeMirror and React into the main process.
//
//   bun scripts/generate-command-catalogue.ts          writes the file
//   bun scripts/generate-command-catalogue.ts --check  exits 1 when the file is out of date
//
// tests/main/command-catalogue.test.ts runs the same check, so a command added to the renderer's
// registry without regenerating fails the unit suite.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { allBindableCommands, commandRegistry, isActiveFileCommand } from '../src/renderer/src/commands/registry'
import { defaultChords } from '../src/renderer/src/commands/chords'

export const CATALOGUE_PATH = join(import.meta.dir, '..', 'src', 'shared', 'command-catalogue.ts')

export function catalogueSource(): string {
  const bindable = new Set(allBindableCommands().map((command) => command.id))
  const rows = commandRegistry
    .filter((command) => command.surfaces.includes('palette'))
    .map((command) => ({
      id: command.id,
      label: command.label,
      task: command.task,
      // The Files pane owns these default chords. The matching palette action has no global
      // default, but it can have its own user-assigned chord.
      keys: command.keysPlaceBound && isActiveFileCommand(command.id) ? [] : defaultChords(command),
      bindable: bindable.has(command.id),
    }))
  const lines = rows.map((row) => `  ${JSON.stringify(row)},`)
  return [
    '// GENERATED by scripts/generate-command-catalogue.ts from src/renderer/src/commands/registry.ts. Do not edit.',
    '// Every palette command: its id, label, task group, default chords (display spelling, ⌃⌥⇧⌘ order)',
    '// and whether Settings › Shortcuts may rebind it. Pure data for main, the CLI and the Settings window.',
    '',
    'export type CatalogueRow = { id: string; label: string; task: string; keys: string[]; bindable: boolean }',
    '',
    'export const COMMAND_CATALOGUE: readonly CatalogueRow[] = [',
    ...lines,
    ']',
    '',
  ].join('\n')
}

if (import.meta.main) {
  const next = catalogueSource()
  if (process.argv.includes('--check')) {
    let current = ''
    try { current = readFileSync(CATALOGUE_PATH, 'utf8') } catch { /* missing counts as stale */ }
    if (current !== next) {
      process.stderr.write('src/shared/command-catalogue.ts is out of date: run bun scripts/generate-command-catalogue.ts\n')
      process.exit(1)
    }
  } else {
    writeFileSync(CATALOGUE_PATH, next)
  }
}
